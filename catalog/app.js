function startQuiz() {
  answers = new Array(curQuiz.questions.length).fill(null);
  curQ = 0;
  showQuestion();
}

function showQuestion() {
  var q = curQuiz;
  var questions = q.questions;
  var question = questions[curQ];
  var isTf = q.format === 'tf';
  var ansCount = isTf ? 2 : 4;
  var shapes = isTf ? ['✓', '✗'] : ['◆', '●', '▲', '■'];
  var colors = isTf ? ['#10B981', '#e74c3c'] : ['#6366F1', '#10B981', '#e74c3c', '#f59e0b'];

  // Build shuffled order for this question (same order every time for this session)
  var indices = [];
  for (var i = 0; i < question.a.length; i++) indices.push(i);

  var html = '<div class="q-screen active">' +
    '<div class="q-top">' +
      '<span class="q-num">Вопрос ' + (curQ + 1) + ' из ' + questions.length + '</span>' +
      '<span class="q-timer" id="qTimer"></span>' +
    '</div>' +
    '<div class="q-timer-bar"><div class="q-timer-fill" id="qTimerFill"></div></div>' +
    '<div class="q-text">' + question.q + '</div>' +
    '<div class="q-answers' + (isTf ? ' tf' : '') + '" id="qAnswers">';

  indices.forEach(function(idx) {
    var a = question.a[idx];
    var isSelected = answers[curQ] === idx;
    html += '<button class="ans-btn' + (isSelected ? ' selected' : '') + '" ' +
      'onclick="selectAnswer(' + idx + ')" ' +
      'style="background:' + colors[idx % colors.length] + '">' +
      '<span class="shape">' + shapes[idx % shapes.length] + '</span>' +
      '<span class="text">' + a.t + '</span>' +
    '</button>';
  });

  html += '</div><div class="q-nav">';

  if (curQ > 0) {
    html += '<button class="btn btn-prev" onclick="prevQ()">← Назад</button>';
  }
  if (curQ < questions.length - 1) {
    html += '<button class="btn btn-next" onclick="nextQ()">Далее →</button>';
  } else {
    html += '<button class="btn btn-next" onclick="finishQuiz()" style="background:#10B981">Завершить</button>';
  }

  html += '</div></div>';
  document.getElementById('playerBody').innerHTML = html;

  // Start timer
  startTimer();
}

function selectAnswer(idx) {
  answers[curQ] = idx;
  showQuestion();
}

function nextQ() {
  if (curQ < curQuiz.questions.length - 1) {
    curQ++;
    showQuestion();
  }
}

function prevQ() {
  if (curQ > 0) {
    curQ--;
    showQuestion();
  }
}

function startTimer() {
  clearInterval(timerInterval);
  var total = 30;
  timeLeft = total;
  var timerEl = document.getElementById('qTimer');
  var fillEl = document.getElementById('qTimerFill');
  if (!timerEl) return;

  function tick() {
    if (timeLeft <= 0) {
      clearInterval(timerInterval);
      if (curQ < curQuiz.questions.length - 1) nextQ();
      else finishQuiz();
      return;
    }
    timeLeft--;
    var pct = (timeLeft / total) * 100;
    timerEl.textContent = timeLeft + 'с';
    timerEl.classList.toggle('urgent', timeLeft <= 10);
    if (fillEl) {
      fillEl.style.width = pct + '%';
      fillEl.classList.toggle('urgent', timeLeft <= 10);
    }
  }

  timerEl.textContent = total + 'с';
  if (fillEl) fillEl.style.width = '100%';
  timerInterval = setInterval(tick, 1000);
}

