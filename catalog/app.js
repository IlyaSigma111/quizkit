// ---- CATALOG LOGIC ----
function getCategories() {
  var cats = {};
  QUIZZES.forEach(function(q) { cats[q.category] = (cats[q.category] || 0) + 1; });
  return cats;
}

function getFormats() {
  var fmts = {};
  QUIZZES.forEach(function(q) { fmts[q.format] = (fmts[q.format] || 0) + 1; });
  return fmts;
}

function toggleFav(id, e) {
  if (e) e.stopPropagation();
  var i = favs.indexOf(id);
  if (i > -1) favs.splice(i, 1); else favs.push(id);
  localStorage.setItem('ilya-favs', JSON.stringify(favs));
  renderGrid();
  updateCounts();
}

function updateCounts() {
  document.getElementById('totalCount').textContent = QUIZZES.length + ' викторин';
  document.getElementById('favCount').textContent = '★ ' + favs.length;
}

function renderFilters() {
  var cats = getCategories();
  var catHtml = '<button class="chip active" onclick="setCat(\'Все\')">Все</button>';
  Object.keys(cats).sort().forEach(function(c) {
    catHtml += '<button class="chip" onclick="setCat(\'' + c + '\')">' + c + ' (' + cats[c] + ')</button>';
  });
  document.getElementById('catChips').innerHTML = catHtml;

  var fmtMap = { quiz: 'Викторина', tf: 'Правда/Ложь', test: 'Проверочная' };
  var fmts = getFormats();
  var fmtHtml = '<button class="fmt active" onclick="setFmt(\'Все\')">Все</button>';
  Object.keys(fmts).sort().forEach(function(f) {
    fmtHtml += '<button class="fmt" onclick="setFmt(\'' + f + '\')">' + (fmtMap[f] || f) + '</button>';
  });
  document.getElementById('fmtChips').innerHTML = fmtHtml;
}

function setCat(c) {
  activeCat = c;
  document.querySelectorAll('#catChips .chip').forEach(function(el) {
    el.classList.toggle('active', el.textContent.indexOf(c) === 0 || (c === 'Все' && el.textContent === 'Все'));
  });
  renderGrid();
}

function setFmt(f) {
  activeFmt = f;
  document.querySelectorAll('#fmtChips .fmt').forEach(function(el, i) {
    var all = document.querySelectorAll('#fmtChips .fmt');
    all.forEach(function(e) { e.classList.remove('active'); });
    if (f === 'Все') all[0].classList.add('active');
    else {
      var fmtMap = { quiz: 'Викторина', tf: 'Правда/Ложь', test: 'Проверочная' };
      if (el.textContent === fmtMap[f]) el.classList.add('active');
    }
  });
  renderGrid();
}

function renderGrid() {
  var grid = document.getElementById('quizGrid');
  var filtered = QUIZZES.filter(function(q) {
    if (activeCat !== 'Все' && q.category !== activeCat) return false;
    if (activeFmt !== 'Все' && q.format !== activeFmt) return false;
    if (searchQ && q.title.toLowerCase().indexOf(searchQ) === -1 && q.desc.toLowerCase().indexOf(searchQ) === -1) return false;
    return true;
  });

  if (filtered.length === 0) {
    grid.innerHTML = '<div class="empty-state"><div class="icon">🔍</div><p>Ничего не найдено</p></div>';
    return;
  }

  var fmtLabels = { quiz: 'Викторина', tf: 'Правда/Ложь', test: 'Проверочная' };
  var fmtClass = { quiz: 'tag-quiz', tf: 'tag-tf', test: 'tag-test' };

  grid.innerHTML = filtered.map(function(q) {
    var isFav = favs.indexOf(q.id) > -1;
    return '<div class="card" onclick="openPlayer(\'' + q.id + '\')">' +
      '<div class="card-top">' +
        '<div class="card-emoji">' + q.emoji + '</div>' +
        '<button class="card-fav' + (isFav ? ' active' : '') + '" onclick="toggleFav(\'' + q.id + '\', event)">' + (isFav ? '♥' : '♡') + '</button>' +
      '</div>' +
      '<h3>' + q.title + '</h3>' +
      '<p class="card-desc">' + q.desc + '</p>' +
      '<div class="card-meta">' +
        '<span class="tag ' + (fmtClass[q.format] || 'tag-quiz') + '">' + (fmtLabels[q.format] || q.format) + '</span>' +
        '<span class="tag tag-cat">' + q.category + '</span>' +
        '<span class="tag tag-cat">' + q.questions.length + ' вопросов</span>' +
      '</div>' +
      '<div class="card-actions">' +
        '<button class="btn btn-play">▶ Играть</button>' +
        '<button class="btn btn-preview" onclick="previewQuiz(\'' + q.id + '\', event)">👁</button>' +
      '</div>' +
    '</div>';
  }).join('');
}

