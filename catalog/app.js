function testSelect(qi, ai) {
  answers[qi] = ai;
  // Update visual
  curQuiz.questions[qi].a.forEach(function(_, bi) {
    var btn = document.getElementById('tbtn-' + qi + '-' + bi);
    if (btn) btn.classList.toggle('selected', bi === ai);
  });
}

// ---- RESULTS ----
function finishQuiz() {
  clearInterval(timerInterval);
  if (!curQuiz) return;
  var q = curQuiz;
  var correct = 0;
  var total = q.questions.length;
  var details = [];

  q.questions.forEach(function(question, qi) {
    var userAns = answers[qi];
    var correctIdx = -1;
    question.a.forEach(function(a, ai) { if (a.c) correctIdx = ai; });
    var isCorrect = userAns === correctIdx;
    if (isCorrect) correct++;

    var userText = userAns !== null ? question.a[userAns].t : 'Нет ответа';
    var correctText = question.a[correctIdx].t;
    details.push({
      q: question.q,
      user: userText,
      correct: correctText,
      ok: isCorrect
    });
  });

  var pct = Math.round((correct / total) * 100);
  var icon = pct >= 80 ? '🏆' : pct >= 50 ? '👍' : '📚';
  var msg = pct >= 80 ? 'Отлично!' : pct >= 50 ? 'Хороший результат!' : 'Нужно подучить!';

  var html = '<div class="result-screen active">' +
    '<div class="result-icon">' + icon + '</div>' +
    '<div class="result-title">' + msg + '</div>' +
    '<div class="result-points">' + correct + ' / ' + total + '</div>' +
    '<div class="result-sub">' + pct + '% правильных ответов</div>' +
    '<div class="result-list">';

  details.forEach(function(d) {
    html += '<div class="result-row">' +
      '<span class="icon">' + (d.ok ? '✅' : '❌') + '</span>' +
      '<span class="q">' + d.q + '</span>' +
      '<span class="a ' + (d.ok ? 'ok' : 'bad') + '">' + (d.ok ? d.user : d.correct) + '</span>' +
    '</div>';
  });

  html += '</div>' +
    '<button class="btn-restart" onclick="restartQuiz()">Играть снова</button>' +
    '</div>';

  document.getElementById('playerBody').innerHTML = html;
}

function restartQuiz() {
  curQ = 0;
  answers = [];
  showLobby();
}

